import { spawn } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { prepareSmokeDatabase } from "./smoke-db.mjs";

/**
 * Persistent dev DB lane (sprint-4 Q1=c). prepareSmokeDatabase() spins up an
 * ephemeral docker MySQL with random port + project name, runs migrate + seed,
 * and normally returns a stop() function for teardown. This wrapper *skips*
 * stop() so the container survives across multiple persona:turn invocations
 * (학습 사용 흐름). Cleanup is the `down <project>` subcommand.
 *
 * stdout contract (locked by plan §5.1 S3):
 *   line N-1: `DATABASE_URL=mysql://study_note:study_note@127.0.0.1:<port>/study_note`
 *   line N:   `COMPOSE_PROJECT=study-note-dev-persistent-<ts>-<rand>`
 *
 * Usage:
 *   eval "$(node scripts/db-persistent.mjs up | tail -n 2)"
 *   export DATABASE_URL COMPOSE_PROJECT
 *   STUDY_NOTE_LLM_REAL_OPT_IN=1 npm run persona:turn -- --subject ... --query ...
 *   node scripts/db-persistent.mjs down "$COMPOSE_PROJECT"
 */

const composeFile = resolve("backend/prisma/docker-compose.smoke.yml");
const subcommand = process.argv[2] ?? "up";

if (subcommand === "up") {
  // Gate 6 codex CPO finding: STUDY_NOTE_USE_EXISTING_DB=1 routes prepareSmokeDatabase
  // to a branch that does not own a docker compose project, so this lane cannot teardown
  // the DB. Refuse explicitly instead of printing an empty COMPOSE_PROJECT.
  if (process.env.STUDY_NOTE_USE_EXISTING_DB === "1") {
    process.stderr.write(
      "[db-persistent] up: STUDY_NOTE_USE_EXISTING_DB=1 is unsupported in this lane (no docker compose project to teardown). unset it and retry, or manage the external DB yourself.\n"
    );
    process.exit(1);
  }
  const db = await prepareSmokeDatabase("dev-persistent");
  if (!db.composeProject) {
    process.stderr.write(
      "[db-persistent] up: prepareSmokeDatabase returned no composeProject — refusing to print incomplete teardown handle.\n"
    );
    await db.stop?.();
    process.exit(1);
  }
  // sprint-5 round 4 (사용자 요청 — 매번 export 불편 fix): .env 자동 write.
  // npm scripts 가 `node --env-file-if-exists=.env ...` 로 자동 load.
  // sprint-1 (W19) PII fixture cleanup: 사용자가 .env 에 직접 둔
  // STUDY_NOTE_* 변수 (예: USER 이메일) 는 매 db:up 마다 사라지면 곤란하므로 보존.
  // 단, db-persistent 가 직접 관리하는 STUDY_NOTE_LLM_TIMEOUT_MS 는 보존 대상에서 제외.
  let preservedUserEnv = "";
  try {
    const existing = await readFile(resolve(".env"), "utf8");
    const userLines = existing.split("\n").filter(
      (line) => /^STUDY_NOTE_/.test(line) && !/^STUDY_NOTE_LLM_TIMEOUT_MS=/.test(line)
    );
    if (userLines.length > 0) {
      preservedUserEnv =
        "\n# preserved from prior .env (user-managed STUDY_NOTE_* env)\n" +
        userLines.join("\n");
    }
  } catch {
    // no prior .env — first run.
  }
  const envContent =
    [
      `# auto-generated by db-persistent.mjs at ${new Date().toISOString()} — overwritten on every db:up-persistent`,
      `DATABASE_URL=${db.databaseUrl}`,
      `COMPOSE_PROJECT=${db.composeProject}`,
      `SESSION_TOKEN_PEPPER=${db.sessionTokenPepper}`,
      `PORT=3001`,
      `HOST=0.0.0.0`,
      `STUDY_NOTE_LLM_TIMEOUT_MS=120000`
    ].join("\n") +
    preservedUserEnv +
    "\n";
  await writeFile(resolve(".env"), envContent, "utf8");

  process.stdout.write("[db-persistent] up — container is running, stop() intentionally skipped\n");
  process.stdout.write("[db-persistent] .env auto-written. now `npm run dev:backend` / `ingest:pdf` 등이 자동 load.\n");
  process.stdout.write(`DATABASE_URL=${db.databaseUrl}\n`);
  process.stdout.write(`COMPOSE_PROJECT=${db.composeProject}\n`);
  // we deliberately do NOT call db.stop() — container persists.
} else if (subcommand === "down") {
  const projectArg = process.argv[3] ?? process.env.COMPOSE_PROJECT;
  if (!projectArg) {
    process.stderr.write(
      "[db-persistent] usage: node scripts/db-persistent.mjs down <COMPOSE_PROJECT>\n"
    );
    process.exit(1);
  }
  await spawnAndAwait("docker", [
    "compose",
    "-p",
    projectArg,
    "-f",
    composeFile,
    "down",
    "-v",
    "--remove-orphans"
  ]);
  process.stdout.write(`[db-persistent] down — project=${projectArg} torn down\n`);
} else {
  process.stderr.write(
    `[db-persistent] unknown subcommand: ${subcommand}. usage: up | down <COMPOSE_PROJECT>\n`
  );
  process.exit(1);
}

async function spawnAndAwait(cmd, args) {
  const child = spawn(cmd, args, { stdio: ["ignore", "pipe", "pipe"] });
  let stderr = "";
  child.stderr.on("data", (c) => {
    stderr += String(c);
  });
  child.stdout.on("data", (c) => process.stdout.write(c));
  const exitCode = await new Promise((resolve) => child.on("close", resolve));
  if (exitCode !== 0) {
    process.stderr.write(stderr);
    throw new Error(`${cmd} ${args.join(" ")} exited ${exitCode}`);
  }
}
